def fill_and_compile():
    for locale, strings in TRANSLATIONS.items():
        merged = {**strings, **LEGAL_TRANSLATIONS.get(locale, {})}
        po_path = TRANSLATIONS_DIR / locale / 'LC_MESSAGES' / 'messages.po'
        mo_path = TRANSLATIONS_DIR / locale / 'LC_MESSAGES' / 'messages.mo'

        with po_path.open('rb') as f:
            catalog = read_po(f, locale=locale)

        for message in catalog:
            if message.id and message.id in merged:
                message.string = merged[message.id]
            elif message.id and isinstance(message.id, tuple):
                joined = ''.join(message.id)
                if joined in merged:
                    message.string = merged[joined]

        catalog.fuzzy = False
        catalog.locale = locale

        with po_path.open('wb') as f:
            write_po(f, catalog)

        with mo_path.open('wb') as f:
            write_mo(f, catalog)

        print(f'Compiled {locale}')


if __name__ == '__main__':
    fill_and_compile()
